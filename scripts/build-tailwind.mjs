// build-tailwind.mjs - dist/tailwind.css 생성 (Tailwind v4 소비자용 토큰 브리지)
//
// theme.scss 의 CSS 변수 이름만 읽어 `@theme inline` 으로 매핑한다. 값은 복사하지 않고 var() 로 가리키므로
// light/dark 전환·테마 덮어쓰기가 style.css 와 그대로 연동되고, theme.scss 에 변수가 늘면 자동으로 따라온다.
//   --bt-color-text-heading → --color-bt-text-heading → `text-bt-text-heading`
//   --bt-elevation-level2   → --shadow-bt-level2       → `shadow-bt-level2`
// 변수 정의(:root)는 style.css 가 공급하므로 이 파일만으로는 색이 나오지 않는다.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync("src/styles/theme.scss", "utf-8");
const names = [...new Set(theme.match(/^\s*--bt-[a-z0-9-]+(?=\s*:)/gm).map((n) => n.trim()))];

const map = (prefix, to) =>
	names
		.filter((n) => n.startsWith(prefix))
		.map((n) => `\t${to}${n.slice(prefix.length)}: var(${n});`);

const colors = map("--bt-color-", "--color-bt-");
const shadows = [
	...map("--bt-elevation-", "--shadow-bt-"),
	...map("--bt-focus-ring", "--shadow-bt-focus-ring"),
];

if (colors.length === 0 || shadows.length === 0) {
	console.error("❌ theme.scss 에서 --bt-color-* / --bt-elevation-* 를 찾지 못했습니다");
	process.exit(1);
}

const css = `/* @bigtablet/design-system - Tailwind v4 theme bridge (generated by scripts/build-tailwind.mjs) */

/* style.css 와 같은 레이어 순서. \`@import "tailwindcss"\` 보다 먼저 import 하면 CSS 로드 순서와 무관하게
   리셋(base) < DS(bigtablet) < 유틸리티 가 고정된다 */
@layer theme, base, reset, bigtablet, components, utilities;

/* ThemeProvider 와 같은 규칙: data-theme="dark" 명시 또는 data-theme 없을 때 OS 다크 */
@custom-variant dark {
	&:where([data-theme="dark"], [data-theme="dark"] *) {
		@slot;
	}
	@media (prefers-color-scheme: dark) {
		&:where(:root:not([data-theme]), :root:not([data-theme]) *) {
			@slot;
		}
	}
}

@theme inline {
${colors.join("\n")}

${shadows.join("\n")}
}
`;

mkdirSync("dist", { recursive: true });
writeFileSync("dist/tailwind.css", css);
console.log(
	`✓ Tailwind theme: ${colors.length} colors, ${shadows.length} shadows → dist/tailwind.css`,
);
